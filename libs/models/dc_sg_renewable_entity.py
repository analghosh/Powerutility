"""
DC SG Renewable Entity Model
Intermediate staging layer for renewable data before promotion to renewable_serve.
Unique key: scheduled_at, plant_id, time_block, type
"""

from datetime import datetime
from typing import Optional
from pydantic import BaseModel, Field, ConfigDict
from libs.enum.updated_flag import UpdatedFlag


class DcSgRenewableEntity(BaseModel):
    """
    DC SG Renewable staging entity.

    Role: Intermediate collection between raw renewable data and renewable_serve.
    Data flows: raw → dc_sg_renewable (upsert) → renewable_serve (upsert)

    Unique constraint: (scheduled_at, plant_id, time_block, type)
    """

    model_config = ConfigDict(
        validate_by_name=True,
        arbitrary_types_allowed=True,
        json_encoders={
            datetime: lambda v: v.isoformat()
        }
    )

    # Unique key fields
    scheduled_at: datetime = Field(..., description="Schedule date and time")
    plant_id: str = Field(..., description="Plant identifier")
    time_block: Optional[int] = Field(None, description="Time block identifier (1-96)")
    type: Optional[str] = Field(None, description="Renewable energy type (Solar, Wind, Hydro, etc.)")

    # Data fields
    schedule_volume: float = Field(default=0.0, description="Scheduled volume/capacity")
    sg_beforelosses: Optional[float] = Field(None, description="SG Before Losses")
    approval_no: Optional[str] = Field(None, description="Approval number")

    # Revision tracking
    revision_no: Optional[int] = Field(None, description="Revision number from source")
    source_revision_number: Optional[int] = Field(None, description="Source revision number")
    system_revision_number: int = Field(default=1, description="System revision counter (increments on each update)")

    # Process flags
    updated_flag: Optional[str] = Field(default=UpdatedFlag.UPDATED.value, description="Updated flag (UPDATED/REPLACED/OLD)")

    # Source tracking
    source: Optional[str] = Field(
        None,
        description="Data origin: 'upload', 'api', 'dc_sg_rollover' (rolled over from previous day), or other ingestion type"
    )

    # Carry-forward metadata
    carried_forward: bool = Field(default=False, description="True if this record was generated by carry-forward logic")
    carry_source_date: Optional[datetime] = Field(None, description="Original scheduled_at from which this record was carried forward")

    # Timestamps
    created_at: datetime = Field(default_factory=datetime.now, description="Creation timestamp")
    updated_at: datetime = Field(default_factory=datetime.now, description="Last update timestamp")
    inserted_at: datetime = Field(default_factory=datetime.now, description="Insertion timestamp")
